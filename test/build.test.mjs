import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { access, readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { buildIndex, IndexError } from '../src/build.mjs';
import { archifyPage, plainPage, put, scratch } from './helpers.mjs';

const run = promisify(execFile);
const cli = fileURLToPath(new URL('../bin/archify-index.mjs', import.meta.url));
const dataOf = html => JSON.parse(/id="archify-index-data">([\s\S]*?)<\/script>/.exec(html)[1]);
const exists = file => access(file).then(() => true, () => false);

test('a folder gives its Archify pages in natural name order and skips everything else', async t => {
  const dir = await scratch(t);
  await put(dir, {
    'step-10.html': archifyPage({ title: 'Ten' }),
    'step-2.html': archifyPage({ title: 'Two', type: 'sequence' }),
    'notes.html': plainPage,
    'readme.md': '# not a page',
  });
  const first = await buildIndex({ inputs: [dir] });
  assert.equal(first.output, path.join(dir, 'index.html'));
  assert.deepEqual(first.diagrams.map(d => [d.title, d.type, d.href]), [['Two', 'sequence', 'step-2.html'], ['Ten', 'architecture', 'step-10.html']]);
  // A second run over the same folder leaves out the index it wrote before.
  const second = await buildIndex({ inputs: [dir] });
  assert.equal(second.diagrams.length, 2);
});

test('a named file that Archify did not write is refused, and nothing is written', async t => {
  const dir = await scratch(t);
  await put(dir, { 'a.html': archifyPage(), 'notes.html': plainPage });
  await assert.rejects(buildIndex({ inputs: [path.join(dir, 'a.html'), path.join(dir, 'notes.html')] }),
    error => error instanceof IndexError && error.code === 'not-archify');
  assert.equal(await exists(path.join(dir, 'index.html')), false);
});

