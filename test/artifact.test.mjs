import assert from 'node:assert/strict';
import test from 'node:test';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { readFile } from 'node:fs/promises';
import { archifyVersion, decodeEntities, describe, receiptType } from '../src/artifact.mjs';
import { archifyPage, DESCRIPTIONS, plainPage, put, scratch } from './helpers.mjs';

test('reads the title and type of each diagram type, in English and Chinese', () => {
  for (const lang of ['en', 'zh-CN']) {
    for (const type of Object.keys(DESCRIPTIONS.en)) {
      const facts = describe(archifyPage({ title: `A ${type}`, type, lang }), 'fallback');
      assert.deepEqual(facts, { title: `A ${type}`, type, archify: '3.0.1' }, `${lang} ${type}`);
    }
  }
});

test('decodes character references in titles', () => {
  const facts = describe(archifyPage({ title: `Tom & Jerry's <stack> "v2"` }), 'fallback');
  assert.equal(facts.title, `Tom & Jerry's <stack> "v2"`);
  assert.equal(decodeEntities('&#x4e2d;&#25991; &unknown; &#0;'), '中文 &unknown; &#0;');
});

test('falls back to the head title without its suffix, then to the file name', () => {
  const headOnly = '<html><head><meta name="generator" content="archify 3.0.1"><title>Payments Diagram</title></head></html>';
  assert.equal(describe(headOnly, 'file').title, 'Payments');
  const untitled = '<html><head><meta name="generator" content="archify 3.0.1"></head></html>';
  assert.equal(describe(untitled, 'file-name').title, 'file-name');
  assert.equal(describe(untitled, 'file-name').type, null);
});

test('tells Archify pages from other pages', () => {
  assert.equal(archifyVersion(archifyPage({ version: '3.0.2' })), '3.0.2');
  assert.equal(archifyVersion('<meta name="generator" content="archify">'), 'unknown');
  assert.equal(archifyVersion(plainPage), null);
  assert.equal(archifyVersion('<meta name="generator" content="archify-index 0.1.0">'), null);
});

test('takes the type from Archify\'s delivery receipt only when it describes this exact page', async t => {
  const dir = await scratch(t);
  const page = archifyPage({ title: 'Spanish page', type: 'architecture' }).replace('An architecture diagram generated by Archify.', 'Un diagrama de arquitectura generado por Archify.');
  const digest = createHash('sha256').update(page).digest('hex');
  await put(dir, {
    'a.html': page,
    'a.delivery.json': JSON.stringify({ command: 'deliver', type: 'tree', artifact: { sha256: digest } }),
    'b.html': page,
    'b.delivery.json': JSON.stringify({ command: 'deliver', type: 'tree', artifact: { sha256: '0'.repeat(64) } }),
    'c.html': page,
    'c.delivery.json': JSON.stringify({ type: '--help', artifact: { sha256: digest } }),
  });
  const typeOf = async name => receiptType(path.join(dir, name), await readFile(path.join(dir, name)));
  assert.equal(await typeOf('a.html'), 'tree');
  assert.equal(await typeOf('b.html'), null, 'a receipt for other bytes is ignored');
  assert.equal(await typeOf('c.html'), null, 'a type Archify would never write is ignored');
  assert.equal(describe(page, 'x').type, null, 'the Spanish sentence alone names no type');
});
