test('addresses are relative and encoded; repeated inputs count once; names stay unique', async t => {
  const dir = await scratch(t);
  await put(dir, {
    'one/My Map #1.html': archifyPage({ title: 'First' }),
    'two/my-map-1.html': archifyPage({ title: 'Second' }),
  });
  const a = path.join(dir, 'one/My Map #1.html');
  const receipt = await buildIndex({ inputs: [a, a, path.join(dir, 'two')] });
  assert.equal(receipt.output, path.join(dir, 'index.html'));
  assert.deepEqual(receipt.diagrams.map(d => [d.href, d.slug]), [['one/My%20Map%20%231.html', 'my-map-1'], ['two/my-map-1.html', 'my-map-1-2']]);
  const html = await readFile(receipt.output, 'utf8');
  assert.deepEqual(dataOf(html).diagrams.map(d => d.href), ['one/My%20Map%20%231.html', 'two/my-map-1.html']);
});

