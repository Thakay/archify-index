// Reads what an index needs from a delivered Archify page: that Archify made it, its title and
// its diagram type. It reads files as text and never runs them.

import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

/** A diagram type as Archify names it in specs and receipts. */
export const TYPE_NAME = /^[a-z][a-z0-9-]{0,31}$/;

// The sentence Archify writes into `#archify-diagram-description`, per type, in the two languages
// this tool reads (`diagram.description.*` in Archify's locale catalogs).
const DESCRIPTIONS = {
  architecture: ['An architecture diagram generated by Archify', '由 Archify 生成的架构图'],
  workflow: ['A workflow diagram generated by Archify', '由 Archify 生成的工作流图'],
  sequence: ['A sequence diagram generated by Archify', '由 Archify 生成的时序图'],
  dataflow: ['A data-flow diagram generated by Archify', '由 Archify 生成的数据流图'],
  lifecycle: ['A lifecycle diagram generated by Archify', '由 Archify 生成的生命周期图'],
  erd: ['An entity-relationship diagram generated by Archify', '由 Archify 生成的实体关系图'],
  tree: ['A hierarchy diagram generated by Archify', '由 Archify 生成的层级结构图'],
  class: ['A class and interface diagram generated by Archify', '由 Archify 生成的类与接口图'],
  timeline: ['An event timeline generated by Archify', '由 Archify 生成的事件时间线'],
  waterfall: ['An execution waterfall generated by Archify', '由 Archify 生成的执行瀑布图'],
};

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };

/** Decodes the HTML character references a title may carry. */
export function decodeEntities(text) {
  return text.replace(/&(#x[0-9a-f]+|#[0-9]+|[a-z]+);/gi, (whole, name) => {
    if (name[0] === '#') {
      const code = name[1] === 'x' || name[1] === 'X' ? parseInt(name.slice(2), 16) : parseInt(name.slice(1), 10);
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    return ENTITIES[name.toLowerCase()] ?? whole;
  });
}

const clean = text => decodeEntities(text).replace(/\s+/g, ' ').trim();

/** The Archify version that wrote this page, or null when Archify did not write it. */
export function archifyVersion(html) {
  const match = /<meta\s+name="generator"\s+content="archify(?:\s+([^"]*))?"/i.exec(html);
  return match ? (match[1] ?? '').trim() || 'unknown' : null;
}

/** The facts an index shows for one page. `fallbackTitle` names a page with no title. */
export function describe(html, fallbackTitle) {
  const svgTitle = /<title\s+id="archify-diagram-title"[^>]*>([^<]*)<\/title>/i.exec(html);
  const headTitle = /<head[\s\S]*?<title>([^<]*)<\/title>/i.exec(html);
  let title = svgTitle ? clean(svgTitle[1]) : '';
  if (!title && headTitle) title = clean(headTitle[1]).replace(/\s+Diagram$/, '');
  const descriptionMatch = /id="archify-diagram-description"[^>]*>([^<]*)</i.exec(html);
  const description = descriptionMatch ? clean(descriptionMatch[1]) : '';
  const type = Object.keys(DESCRIPTIONS).find(name => DESCRIPTIONS[name].some(sentence => description.includes(sentence))) ?? null;
  return { title: title || fallbackTitle, type, archify: archifyVersion(html) };
}

/**
 * The type Archify recorded when it delivered this page: read from the `<stem>.delivery.json`
 * receipt beside it, and trusted only when the receipt's artifact hash matches the page's bytes.
 */
export async function receiptType(file, bytes) {
  const receipt = path.join(path.dirname(file), `${path.basename(file).replace(/\.html?$/i, '')}.delivery.json`);
  let data;
  try {
    data = JSON.parse(await readFile(receipt, 'utf8'));
  } catch {
    return null;
  }
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (data?.artifact?.sha256 !== digest || typeof data.type !== 'string' || !TYPE_NAME.test(data.type)) return null;
  return data.type;
}
