const escape = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

/** A page shaped like the head and diagram title of one Archify delivers. */
export function archifyPage({ title = 'Sample', type = 'architecture', lang = 'en', version = '3.0.1' } = {}) {
  return `<!DOCTYPE html>
<html lang="${lang}">
<head>
  <meta charset="UTF-8">
  <meta name="generator" content="archify ${version}">
  <title>${escape(title)}${lang === 'en' ? ' Diagram' : ''}</title>
</head>
<body>
  <p id="theme-seen"></p>
  <svg role="img" aria-labelledby="archify-diagram-title archify-diagram-description">
    <title id="archify-diagram-title">${escape(title)}</title>
    <desc id="archify-diagram-description">${DESCRIPTIONS[lang][type]}</desc>
  </svg>
  <script>
    document.getElementById('theme-seen').textContent = new URLSearchParams(location.search).get('theme') || 'none';
  </script>
</body>
</html>
`;
}

export const plainPage = '<!doctype html><html><head><title>Notes</title></head><body>notes</body></html>\n';

/** A fresh folder for one test, removed after it. */
export async function scratch(t) {
  const folder = await mkdtemp(path.join(os.tmpdir(), 'archify-index-test-'));
  t.after(() => rm(folder, { recursive: true, force: true }));
  return folder;
}

/** Writes `files` ({relative path: contents}) under `folder`. */
export async function put(folder, files) {
  for (const [name, contents] of Object.entries(files)) {
    const file = path.join(folder, name);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, contents);
  }
}
