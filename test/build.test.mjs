// A stand-in for Archify's CLI: `deliver <type> <spec> <out>` writes a page and prints a receipt,
// or fails the way Archify does when the spec says so.
const FAKE_ARCHIFY = `
import { readFileSync, writeFileSync } from 'node:fs';
const [, , command, type, spec, out] = process.argv;
const body = JSON.parse(readFileSync(spec, 'utf8'));
if (body.fail) {
  process.stdout.write(JSON.stringify({ ok: false, diagnostics: [{ code: 'layout/overlap', message: 'Two nodes overlap.' }] }));
  process.exit(1);
}
const title = body.meta.title;
writeFileSync(out, '<html><head><meta name="generator" content="archify 3.0.1"></head><body><svg><title id="archify-diagram-title">' + title + '</title><desc id="archify-diagram-description">A ' + type + ' diagram generated by Archify.</desc></svg></body></html>');
process.stdout.write(JSON.stringify({ ok: true, receiptId: 'r-' + title, command, type }));
`;

test('JSON specs are delivered through Archify into the index folder', async t => {
  const dir = await scratch(t);
  await put(dir, {
    'tools/archify.mjs': FAKE_ARCHIFY,
    'specs/flow.json': JSON.stringify({ diagram_type: 'workflow', meta: { title: 'Flow' } }),
    'specs/calls.json': JSON.stringify({ diagram_type: 'sequence', meta: { title: 'Calls' } }),
  });
  const receipt = await buildIndex({
    inputs: [path.join(dir, 'specs/flow.json'), path.join(dir, 'specs/calls.json')],
    out: path.join(dir, 'site/index.html'), archify: path.join(dir, 'tools/archify.mjs'),
  });
  assert.deepEqual(receipt.diagrams.map(d => [d.title, d.type, d.href, d.deliveryReceipt]),
    [['Flow', 'workflow', 'flow.html', 'r-Flow'], ['Calls', 'sequence', 'calls.html', 'r-Calls']]);
  assert.deepEqual((await readdir(path.join(dir, 'site'))).sort(), ['calls.html', 'flow.html', 'index.html']);
});

test('an Archify failure stops the build and names its diagnostics', async t => {
  const dir = await scratch(t);
  await put(dir, {
    'archify.mjs': FAKE_ARCHIFY,
    'bad.json': JSON.stringify({ diagram_type: 'workflow', fail: true, meta: { title: 'Bad' } }),
    'flag.json': JSON.stringify({ diagram_type: '--help' }),
    'good.json': JSON.stringify({ diagram_type: 'sequence', meta: { title: 'Good' } }),
    'broken.json': '{ not json',
  });
  const archify = path.join(dir, 'archify.mjs');
  await assert.rejects(buildIndex({ inputs: [path.join(dir, 'bad.json')], archify, out: path.join(dir, 'out/index.html') }),
    error => error.code === 'render-failed' && /layout\/overlap: Two nodes overlap/.test(error.message));
  await assert.rejects(buildIndex({ inputs: [path.join(dir, 'flag.json')], archify }),
    error => error.code === 'invalid-diagram-type');
  // Every spec is read before Archify delivers any, so a broken one stops the set untouched.
  await assert.rejects(buildIndex({ inputs: [path.join(dir, 'good.json'), path.join(dir, 'broken.json')], archify, out: path.join(dir, 'set/index.html') }),
    error => error.code === 'unreadable-spec');
  assert.equal(await exists(path.join(dir, 'set')), false);
});

test('the command prints help, a receipt, and refusals with a non-zero exit', async t => {
  const dir = await scratch(t);
  await put(dir, { 'a.html': archifyPage({ title: 'Alpha' }) });
  const help = await run(process.execPath, [cli, '--help']);
  assert.match(help.stdout, /^Usage: archify-index/);
  const made = await run(process.execPath, [cli, '--json', '--title', 'Set', path.join(dir, 'a.html')]);
  assert.equal(JSON.parse(made.stdout).diagrams[0].title, 'Alpha');
  const plain = await run(process.execPath, [cli, dir]);
  assert.match(plain.stdout, /^Wrote .*index\.html with 1 diagram\.\n$/);
  await assert.rejects(run(process.execPath, [cli, '--json', path.join(dir, 'missing.html')]), error => {
    assert.equal(error.code, 1);
    assert.equal(JSON.parse(error.stdout).error.code, 'missing-input');
    return true;
  });
  await assert.rejects(run(process.execPath, [cli, '--nope']), error => error.code === 1 && /Unknown option/.test(error.stderr));
});

test('renders real Archify specs when ARCHIFY_BIN names Archify', { skip: !process.env.ARCHIFY_BIN && 'set ARCHIFY_BIN to archify/bin/archify.mjs' }, async t => {
  const dir = await scratch(t);
  // The examples that ship with the Archify under test, so each release gets specs it accepts.
  const specs = path.resolve(path.dirname(process.env.ARCHIFY_BIN), '../examples');
  const names = (await readdir(specs)).filter(name => name.endsWith('.json'));
  const receipt = await buildIndex({
    inputs: names.map(name => path.join(specs, name)), out: path.join(dir, 'index.html'), archify: process.env.ARCHIFY_BIN,
  });
  assert.equal(receipt.diagrams.length, names.length);
  const types = await Promise.all(names.map(async name => JSON.parse(await readFile(path.join(specs, name), 'utf8')).diagram_type));
  assert.deepEqual(receipt.diagrams.map(d => d.type).sort(), types.sort());
});

test('refuses, with a code and before writing anything, every input that would lose or replace a file', async t => {
  const dir = await scratch(t);
  await put(dir, {
    'archify.mjs': FAKE_ARCHIFY,
    'set/a.html': archifyPage({ title: 'A' }), 'set/b.html': archifyPage({ title: 'B' }),
    'set/notes.html': plainPage, 'set/sub.html/x.txt': 'a folder named like a page',
    'empty/readme.md': '# no pages', 'specs/index.json': JSON.stringify({ diagram_type: 'workflow', meta: { title: 'I' } }),
    'specs/notes.json': JSON.stringify({ diagram_type: 'workflow', meta: { title: 'N' } }),
  });
  const set = name => path.join(dir, 'set', name);
  const archify = path.join(dir, 'archify.mjs');
  const refused = async (options, code) => assert.rejects(buildIndex(options), error => error instanceof IndexError && error.code === code);
  await refused({ inputs: [path.join(dir, 'empty')] }, 'no-diagrams');
  await refused({ inputs: [set('a.html'), set('b.html')], out: set('a.html') }, 'would-overwrite');
  await refused({ inputs: [set('a.html')], out: set('notes.html') }, 'would-overwrite');
  await refused({ inputs: [path.join(dir, 'specs/index.json')], out: set('index.html'), archify }, 'duplicate-name');
  await refused({ inputs: [path.join(dir, 'specs/notes.json')], out: set('index.html'), archify }, 'would-overwrite');
  await refused({ inputs: [path.join(dir, 'specs/notes.json')], out: set('index.html'), archify: path.join(dir, 'missing.mjs') }, 'archify-missing');
  await refused({ inputs: [set('a.html')], out: path.join(dir, 'set') }, 'would-overwrite');
  assert.equal(await readFile(set('notes.html'), 'utf8'), plainPage);
  assert.equal(await exists(set('index.html')), false);
  // A folder named like a page is not a page.
  assert.equal((await buildIndex({ inputs: [path.join(dir, 'set')] })).diagrams.length, 2);
});

